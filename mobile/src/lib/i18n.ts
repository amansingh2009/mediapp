export const localeFor = (lang: Language) =>
  lang === "hi" ? "hi-IN" : lang === "ta" ? "ta-IN" : "en-IN";
export const tr = (key: Key, lang: Language = "en") => {
  const translated = words[key];
  return translated?.[lang === "hi" ? 1 : lang === "ta" ? 2 : 0] ?? translated?.[0] ?? key;
};
export const errorKey = (error: unknown): Key =>
  error instanceof Error && error.message in words
    ? (error.message as Key)
    : "networkError";
